#pragma once

#include <JuceHeader.h>
#include <functional>

// ============================================================================
// 描き直しをまとめる
// ============================================================================
// 波形のプレビューは、実際に音を作る処理を回して線を引いている。値を 1 つ
// 変えるたびに作り直すと、項目の多いファイルを読み込んだときに目に見えて
// 遅くなる。オペレータが 4 つある音源では、1 回の読み込みで数百回の
// 作り直しが走る。
//
// 読み込みの間は作り直しを溜めておき、読み終えてから 1 度だけ行う。同じ
// 部品からの求めは後のもので上書きするので、何度求められても作り直しは
// 1 回で済む。
namespace GuiRefresh
{
	// 読み込みの間これを置いておく。消えるときに溜めた作り直しを行う。
	class Batch
	{
	public:
		Batch();
		~Batch();
	};

	// まとめている最中なら溜めて true を返す。呼び出し側はそこで戻る。
	// 溜めた側は、まとめが終わったときに同じ関数をもう一度呼ぶ。そのときは
	// まとめていないので、そのまま作り直しが行われる。
	bool defer(const void* owner, std::function<void()> update);
}
